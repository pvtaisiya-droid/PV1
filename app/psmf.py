def source_data_for_block(
    db: Session,
    block: PSMFBlock,
    partner: Partner | None,
) -> dict[str, Any]:
    source = block.source_module
    if source == "all_partners":
        partners = (
            db.query(Partner)
            .filter(
                Partner.is_deleted.is_(False),
                Partner.is_active.is_(True),
            )
            .order_by(Partner.partner_name.asc())
            .all()
        )
        rows = [
            (
                row.partner_code or "",
                row.partner_name or "",
                row.address or "",
            )
            for row in partners
        ]
        return table_source(
            "Держатели регистрационных удостоверений",
            ["Код", "Наименование", "Адрес"],
            rows,
        )

    if source == "partners":
        if not partner:
            return empty_source("Партнер не выбран.")
        rows = [
            ("Код партнера", partner.partner_code or ""),
            ("Название", partner.partner_name or ""),
            ("Адрес", partner.address or ""),
        ]
        return table_source("Сведения о партнере", ["Поле", "Значение"], rows)

    if source == "contracts":
        contracts = []
        if partner:
            contracts = (
                db.query(Contract)
                .filter(Contract.partner_id == partner.id, Contract.is_deleted.is_(False))
                .order_by(Contract.contract_date.desc())
                .all()
            )
        rows = [
            (
                contract.contract_number,
                contract.contract_type,
                str(contract.contract_date),
                str(contract.valid_until),
                ", ".join(product.product_name for product in contract.linked_products),
            )
            for contract in contracts
        ]
        return table_source("Договоры партнера", ["Номер", "Тип", "Дата", "Действует до", "Препараты"], rows)

    if source == "products":
        products = partner_products(db, partner) if partner else []
        rows = [
            (
                product.product_code,
                product.product_name,
                product.dosage_form_name_ru,
                product.authorization_number or "",
                product.authorization_status or "",
            )
            for product in products
        ]
        return table_source("Препараты партнера", ["Код", "Название", "Форма", "РУ", "Статус"], rows)

    if source == "sops":
        sops = (
            db.query(SOP)
            .filter(SOP.is_deleted.is_(False))
            .order_by(SOP.sop_code.asc())
            .all()
        )
        rows = [
            (
                sop.sop_code,
                sop.title,
                sop.version,
                sop.status,
                sop.process_area,
                str(sop.next_review_date),
            )
            for sop in sops
        ]
        return table_source("SOP", ["Код", "Название", "Версия", "Статус", "Процесс", "Review"], rows)

    if source == "psur":
        product_ids = {product.id for product in partner_products(db, partner)} if partner else set()
        query = db.query(PSURPlan).filter(PSURPlan.is_deleted.is_(False))
        if product_ids:
            query = query.filter(PSURPlan.product_id.in_(product_ids))
        plans = query.order_by(PSURPlan.reporting_period_end.desc()).all()
        rows = [
            (
                plan.psur_type,
                plan.product.product_name if plan.product else "",
                str(plan.reporting_period_start),
                str(plan.reporting_period_end),
                plan.status,
            )
            for plan in plans
        ]
        return table_source("ПООБ/PBRER", ["Тип", "Препарат", "Период с", "Период по", "Статус"], rows)

    return empty_source("Источник данных пока не подключен.")


def partner_products(db: Session, partner: Partner | None) -> list[Product]:
    if not partner:
        return []
    return crud.list_products_for_partner(db, partner.id)


def empty_source(message: str) -> dict[str, Any]:
    return {"title": "Нет данных", "headers": [], "rows": [], "text": message, "count": 0}


def table_source(title: str, headers: list[str], rows: list[tuple[Any, ...]]) -> dict[str, Any]:
    if not rows:
        return {"title": title, "headers": headers, "rows": [], "text": DEFAULT_EMPTY_STATE_TEXT, "count": 0}
    lines = [title, " | ".join(headers)]
    for row in rows:
        lines.append(" | ".join(str(value or "") for value in row))
    return {"title": title, "headers": headers, "rows": rows, "text": "\n".join(lines), "count": len(rows)}


def render_block_for_partner(
    db: Session,
    block: PSMFBlock,
    partner: Partner,
    settings: PSMFSettings,
) -> dict[str, Any]:
    version = current_block_version(block)
    source_data = source_data_for_block(db, block, partner) if block.block_type == "AUTO_TABLE_BLOCK" else None
    if block.block_type == "AUTO_TABLE_BLOCK":
        content = source_data["text"] if source_data and source_data["count"] else settings.default_empty_state_text
    elif block.block_type == "EMPTY_STATE_BLOCK":
        content = settings.default_empty_state_text
    elif version:
        content = version.content
    else:
        content = DEFAULT_COMPONENT_TEXT
    content = content.replace("{{partner_name}}", partner.partner_name)
    return {
        "block": block,
        "version": version,
        "content": content,
        "source_data": source_data,
    }


def normalized_psmf_text(value: str | None) -> str:
    return " ".join((value or "").split())


def is_empty_partner_specific_block(block_row: dict[str, Any], settings: PSMFSettings) -> bool:
    block = block_row["block"]
    if block.block_type != "PARTNER_BLOCK":
        return False
    source_data = block_row.get("source_data")
    if source_data is not None and source_data.get("count", 0) == 0:
        return True
    content = normalized_psmf_text(block_row.get("content"))
    empty_texts = {
        "",
        normalized_psmf_text(DEFAULT_COMPONENT_TEXT),
        normalized_psmf_text(DEFAULT_EMPTY_STATE_TEXT),
        normalized_psmf_text(settings.default_empty_state_text),
    }
    return content in empty_texts


def is_empty_component_content(content: str | None, settings: PSMFSettings) -> bool:
    normalized_content = normalized_psmf_text(content)
    empty_texts = {
        "",
        normalized_psmf_text(DEFAULT_COMPONENT_TEXT),
        normalized_psmf_text(DEFAULT_EMPTY_STATE_TEXT),
        normalized_psmf_text(settings.default_empty_state_text),
    }
    return normalized_content in empty_texts


def build_partner_psmf(db: Session, partner_id: str) -> dict[str, Any] | None:
    partner = (
        db.query(Partner)
        .filter(Partner.id == partner_id, Partner.is_deleted.is_(False))
        .first()
    )
    if not partner:
        return None
    settings = get_psmf_settings(db)
    components = list_psmf_components(db)
    rows = []
    for component in components:
        if component.is_optional and not should_include_optional_component(component, settings):
            continue
        version = current_version(component)
        content = (version.content if version else DEFAULT_COMPONENT_TEXT).replace(
            "{{partner_name}}",
            partner.partner_name,
        )
        applicable_blocks = [
            block
            for block in component.blocks
            if not block.is_deleted
            and (
                not is_partner_specific_block(block)
                or block.partner_id is None
                or block.partner_id == partner.id
            )
        ]
        rendered_block_rows = [
            render_block_for_partner(db, block, partner, settings)
            for block in applicable_blocks
        ]
        block_rows = rendered_block_rows
        if settings.skip_empty_partner_specific_blocks:
            block_rows = [
                block_row
                for block_row in rendered_block_rows
                if not is_empty_partner_specific_block(block_row, settings)
            ]
            if rendered_block_rows and not block_rows and is_empty_component_content(content, settings):
                continue
        rows.append(
            {
                "component": component,
                "version": version,
                "content": content,
                "blocks": block_rows,
            }
        )
    warnings = collect_psmf_warnings(db, partner_id=partner.id, rows=rows)
    return {
        "partner": partner,
        "rows": rows,
        "warnings": warnings,
        "generated_at": utcnow(),
        "settings": settings,
    }


def should_include_optional_component(component: PSMFComponent, settings: PSMFSettings) -> bool:
    if component.code.startswith("Приложение К"):
        return settings.include_optional_annex_k_if_has_content
    return True


def collect_psmf_warnings(
    db: Session,
    *,
    partner_id: str | None = None,
    rows: list[dict[str, Any]] | None = None,
) -> list[dict[str, str]]:
    partner = None
    if partner_id:
        partner = (
            db.query(Partner)
            .filter(Partner.id == partner_id, Partner.is_deleted.is_(False))
            .first()
        )
    if rows is None:
        components = list_psmf_components(db)
        rows = [
            {
                "component": component,
                "version": current_version(component),
                "content": (current_version(component).content if current_version(component) else ""),
                "blocks": [
                    {
                        "block": block,
                        "version": current_block_version(block),
                        "content": current_block_version(block).content if current_block_version(block) else "",
                        "source_data": source_data_for_block(db, block, partner) if partner and block.source_module else None,
                    }
                    for block in component.blocks
                    if not block.is_deleted
                    and (
                        not is_partner_specific_block(block)
                        or block.partner_id is None
                        or (partner is not None and block.partner_id == partner.id)
                    )
                ],
            }
            for component in components
        ]

    warnings: list[dict[str, str]] = []
    for row in rows:
        component = row["component"]
        version = row["version"]
        approved_version = latest_approved_version(component)
        parent = component.parent
        component_tab = "chapters"
        while parent:
            if parent.code == "9":
                component_tab = "annexes"
                break
            parent = parent.parent
        component_url = f"/psmf?tab={component_tab}&component_id={component.id}"
        if component.is_required and not version:
            warnings.append(warning("BLOCKER", component.code, display_title(component), "Обязательный компонент не имеет версии.", component_url))
        elif component.is_required and not approved_version:
            warnings.append(warning("BLOCKER", component.code, display_title(component), "Нет утвержденной версии обязательного компонента.", component_url))
        elif version and version.status == "draft":
            warnings.append(warning("WARNING", component.code, display_title(component), "Компонент находится в статусе «Черновик».", component_url))
        if "{{" in row["content"] or "}}" in row["content"]:
            warnings.append(warning("WARNING", component.code, display_title(component), "В компоненте остались placeholder-поля.", component_url))

        for block_row in row["blocks"]:
            block = block_row["block"]
            block_version = block_row["version"]
            content = block_row["content"]
            block_url = f"/psmf/blocks/{block.id}/edit"
            if block.is_required and not block_version:
                warnings.append(warning("BLOCKER", block.code, block.title_ru, "Обязательный блок отсутствует.", block_url))
            elif block.is_required and block.block_type != "EMPTY_STATE_BLOCK" and not content.strip():
                warnings.append(warning("BLOCKER", block.code, block.title_ru, "Пустой обязательный блок без официальной информации.", block_url))
            if "{{" in content or "}}" in content:
                warnings.append(warning("WARNING", block.code, block.title_ru, "В блоке остались placeholder-поля.", block_url))
            if block.block_type == "AUTO_TABLE_BLOCK":
                source_data = block_row.get("source_data")
                if not source_data or source_data.get("count", 0) == 0:
                    warnings.append(warning("WARNING", block.code, block.title_ru, "Автотаблица пустая.", block_url))
            if block.block_type == "PARTNER_BLOCK" and block_version:
                if block_version.partner_review_status not in ("approved", "not_required"):
                    warnings.append(warning("WARNING", block.code, block.title_ru, "Партнерский блок не согласован.", block_url))

    if partner_id:
        add_partner_data_warnings(db, partner, warnings)

    unresolved_comments = (
        db.query(PSMFComment)
        .filter(
            PSMFComment.is_deleted.is_(False),
            PSMFComment.comment_status == "open",
        )
        .count()
    )
    if unresolved_comments:
        warnings.append(
            warning(
                "WARNING",
                "COMMENTS",
                "Комментарии",
                f"Есть нерешенные комментарии: {unresolved_comments}.",
                "/psmf?tab=approval",
            )
        )
    return sorted(warnings, key=lambda row: PSMF_WARNING_LEVELS.index(row["level"]))


def add_partner_data_warnings(db: Session, partner: Partner | None, warnings: list[dict[str, str]]) -> None:
    if not partner:
        warnings.append(warning("BLOCKER", "PARTNER", "Партнер", "Данные партнера отсутствуют.", "/psmf?tab=partner"))
        return
    if not partner.address:
        warnings.append(warning("WARNING", "PARTNER", partner.partner_name, "Карточка партнера заполнена не полностью.", f"/partners/{partner.id}"))
    contract_count = (
        db.query(Contract)
        .filter(Contract.partner_id == partner.id, Contract.is_deleted.is_(False))
        .count()
    )
    if not contract_count:
        warnings.append(warning("WARNING", "CONTRACTS", partner.partner_name, "Договоры партнера отсутствуют.", "/contracts"))
    if not partner_products(db, partner):
        warnings.append(warning("WARNING", "PRODUCTS", partner.partner_name, "Препараты партнера отсутствуют.", "/products"))
    sop_count = db.query(SOP).filter(SOP.is_deleted.is_(False)).count()
    if not sop_count:
        warnings.append(warning("WARNING", "SOP", "SOP", "SOP отсутствуют.", "/sops"))


def warning(level: str, code: str, title: str, message: str, fix_url: str) -> dict[str, str]:
    return {"level": level, "code": code, "title": title, "message": message, "fix_url": fix_url}


