def create_new_component_version(
    db: Session,
    component: PSMFComponent,
    *,
    created_by: str,
    user_id: str | None = None,
) -> PSMFComponent:
    if component.status != "approved":
        raise ValueError("Новую версию можно создать только из утвержденного компонента.")

    source_version = latest_approved_version(component) or current_version(component)
    if not source_version:
        raise ValueError("Утвержденная исходная версия не найдена.")

    # Claim both rows before inserting the unique next label. A concurrent
    # creation must fail as a stale write, not as a duplicate-label error.
    component.version += 1
    db.flush([component])
    source_version.row_version += 1
    # Preserve the approved snapshot's business timestamp during the claim.
    flag_modified(source_version, "updated_at")
    db.flush([source_version])
    new_version_number = increment_version(source_version.version)
    new_version = PSMFComponentVersion(
        component_id=component.id,
        version=new_version_number,
        content=source_version.content,
        status="draft",
        change_summary=f"Создана новая версия из утвержденной версии {source_version.version}.",
        created_by=created_by,
        created_by_text=created_by,
        is_locked=False,
    )
    db.add(new_version)
    db.flush()
    component.current_version = new_version_number
    component.current_version_id = new_version.id
    component.status = "draft"
    component.updated_at = utcnow()

    log_psmf_event(
        db,
        entity_type="PSMF_VERSION",
        entity_id=new_version.id,
        action="new_version_created",
        title=display_title(component),
        details=f"Версия {source_version.version} -> {new_version_number}.",
        old_value=source_version.version,
        new_value=new_version_number,
        field_name="version",
        user_id=user_id,
    )
    db.commit()
    db.refresh(component)
    return component


