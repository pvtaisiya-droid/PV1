def get_psmf_settings(db: Session) -> PSMFSettings:
    """Read persisted settings, or display model defaults without saving them."""
    settings = (
        db.query(PSMFSettings)
        .filter(PSMFSettings.is_deleted.is_(False))
        .order_by(PSMFSettings.created_at.asc())
        .first()
    )
    if settings:
        return settings
    # Installation seeds settings explicitly. A preview must not recreate a
    # missing or deliberately deleted row, even for a user with read access.
    return PSMFSettings(**{
        column.key: column.default.arg
        for column in PSMFSettings.__table__.columns
        if column.default is not None and column.default.is_scalar
    })


def psmf_structure_rows(components: list[PSMFComponent]) -> list[dict[str, Any]]:
    by_parent: dict[str | None, list[PSMFComponent]] = {}
    for component in components:
        by_parent.setdefault(component.parent_component_id, []).append(component)
    for siblings in by_parent.values():
        siblings.sort(key=lambda row: (row.component_order or 0, row.code))

    rows: list[dict[str, Any]] = []

    def walk(parent_id: str | None, depth: int) -> None:
        for component in by_parent.get(parent_id, []):
            rows.append(
                {
                    "component": component,
                    "depth": depth,
                    "block_count": len([block for block in component.blocks if not block.is_deleted]),
                    "approved_version": latest_approved_version(component),
                    "current_version": current_version(component),
                }
            )
            walk(component.id, depth + 1)

    walk(None, 0)
    return rows


