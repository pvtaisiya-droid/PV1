def ensure_psmf_seed_data(db: Session) -> None:
    user_id = first_user_id(db)
    ensure_settings_seed(db)
    reference_partner = (
        db.query(Partner)
        .filter(
            Partner.partner_code == PSMF_REFERENCE_PARTNER_CODE,
            Partner.is_deleted.is_(False),
        )
        .first()
    )

    components_by_code: dict[str, PSMFComponent] = {}
    order = 10
    for code, title, component_type, parent_code in MAIN_SEED_ROWS:
        parent = components_by_code.get(parent_code)
        component = ensure_seed_component(
            db,
            code=code,
            title=title,
            component_type=component_type,
            parent=parent,
            component_order=order,
            is_required=True,
            is_optional=False,
            include_if_has_content=False,
            user_id=user_id,
        )
        components_by_code[code] = component
        order += 10

    for code, title, component_type, parent_code, is_required, is_optional in ANNEX_SEED_ROWS:
        parent = components_by_code.get(parent_code)
        component = ensure_seed_component(
            db,
            code=code,
            title=title,
            component_type=component_type,
            parent=parent,
            component_order=order,
            is_required=is_required,
            is_optional=is_optional,
            include_if_has_content=is_optional,
            user_id=user_id,
            initial_version=PSMF_INITIAL_ANNEX_VERSION,
            initial_content="",
            initial_status="approved",
        )
        components_by_code[code] = component
        order += 10

    block_order = 10
    for (
        component_code,
        block_code,
        title,
        block_type,
        source_module,
        is_required,
        include_if_has_content,
    ) in BLOCK_SEED_ROWS:
        component = components_by_code.get(component_code)
        if not component:
            continue
        ensure_seed_block(
            db,
            component=component,
            code=block_code,
            title=title,
            block_type=block_type,
            block_order=block_order,
            source_module=source_module,
            is_required=is_required,
            include_if_has_content=include_if_has_content,
            user_id=user_id,
            partner=reference_partner if block_type == "PARTNER_BLOCK" else None,
            content=PSMF_BLOCK_INITIAL_CONTENT.get(block_code, ""),
            initial_version=PSMF_INITIAL_ANNEX_VERSION,
            initial_status="approved",
        )
        block_order += 10

    apply_legacy_mapping_metadata(db, components_by_code=components_by_code)
    migrate_legacy_dot_one_components(db, components_by_code=components_by_code, user_id=user_id)
    db.commit()


