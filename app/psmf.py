def build_partner_docx_bytes(preview: dict[str, Any], build: PSMFPartnerBuild) -> bytes:
    document_xml = psmf_docx_document_xml(preview, build)
    output = BytesIO()
    with ZipFile(output, "w", ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", docx_content_types_xml())
        archive.writestr("_rels/.rels", docx_package_rels_xml())
        archive.writestr("word/document.xml", document_xml)
    return output.getvalue()


def psmf_docx_document_xml(preview: dict[str, Any], build: PSMFPartnerBuild) -> str:
    partner = preview["partner"]
    settings = preview["settings"]
    generated_at = preview["generated_at"].strftime("%Y-%m-%d %H:%M")
    body = [
        docx_paragraph("Мастер-файл системы фармаконадзора", bold=True),
        docx_paragraph(f"Компания: {settings.company_name}"),
        docx_paragraph(f"Партнерская сборка: {partner.partner_name}"),
        docx_paragraph(f"Тип сборки: {build.build_type}"),
        docx_paragraph(f"Версия сборки: {build.version}"),
        docx_paragraph(f"Дата формирования: {generated_at}"),
        docx_paragraph(f"Сформировал: {build.generated_by_text or ''}"),
        docx_page_break(),
        docx_paragraph("Лист утверждения", bold=True),
        docx_paragraph("Утвердил: ______________________________"),
        docx_paragraph("Дата: ______________________________"),
        docx_paragraph("Комментарий: ______________________________"),
        docx_page_break(),
        docx_paragraph("Предупреждения комплектности", bold=True),
    ]
    if preview["warnings"]:
        body.append(
            docx_table(
                [["Уровень", "Код", "Объект", "Сообщение"]]
                + [
                    [row["level"], row["code"], row["title"], row["message"]]
                    for row in preview["warnings"]
                ]
            )
        )
    else:
        body.append(docx_paragraph("Предупреждений нет."))
    body.append(docx_page_break())
    body.append(docx_paragraph("Содержание сборки", bold=True))
    for row in preview["rows"]:
        component = row["component"]
        version = row["version"]
        body.append(docx_paragraph(f"{component.code}. {display_title(component)}", bold=True))
        body.append(docx_paragraph(f"Версия: {version.version if version else 'нет'}; статус: {PSMF_STATUS_LABELS.get(component.status, component.status)}"))
        body.append(docx_paragraph(row["content"]))
        for block_row in row["blocks"]:
            block = block_row["block"]
            block_version = block_row["version"]
            body.append(docx_paragraph(f"{block.title_ru}", bold=True))
            body.append(
                docx_paragraph(
                    f"Тип: {PSMF_BLOCK_TYPE_LABELS.get(block.block_type, block.block_type)}; "
                    f"версия: {block_version.version if block_version else 'нет'}"
                )
            )
            body.append(docx_paragraph(block_row["content"]))
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        f"<w:body>{''.join(body)}<w:sectPr/></w:body></w:document>"
    )


def docx_paragraph(text: object, *, bold: bool = False) -> str:
    text_xml = xml_escape(str(text or ""))
    run = f"<w:r><w:t>{text_xml}</w:t></w:r>"
    if bold:
        run = f"<w:r><w:rPr><w:b/></w:rPr><w:t>{text_xml}</w:t></w:r>"
    return f"<w:p>{run}</w:p>"


def docx_page_break() -> str:
    return '<w:p><w:r><w:br w:type="page"/></w:r></w:p>'


def docx_table(rows: list[list[object]]) -> str:
    row_xml = []
    for row in rows:
        cells = "".join(f"<w:tc>{docx_paragraph(cell)}</w:tc>" for cell in row)
        row_xml.append(f"<w:tr>{cells}</w:tr>")
    return "<w:tbl>" + "".join(row_xml) + "</w:tbl>"


def docx_content_types_xml() -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
        "</Types>"
    )


def docx_package_rels_xml() -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>'
        "</Relationships>"
    )


def list_partner_builds(db: Session, partner_id: str | None = None) -> list[PSMFPartnerBuild]:
    query = (
        db.query(PSMFPartnerBuild)
        .options(joinedload(PSMFPartnerBuild.partner), selectinload(PSMFPartnerBuild.items))
        .filter(PSMFPartnerBuild.is_deleted.is_(False))
    )
    if partner_id:
        query = query.filter(PSMFPartnerBuild.partner_id == partner_id)
    return query.order_by(PSMFPartnerBuild.generated_at.desc()).all()


def get_partner_build(db: Session, build_id: str) -> PSMFPartnerBuild | None:
    return (
        db.query(PSMFPartnerBuild)
        .options(joinedload(PSMFPartnerBuild.partner), selectinload(PSMFPartnerBuild.items))
        .filter(PSMFPartnerBuild.id == build_id, PSMFPartnerBuild.is_deleted.is_(False))
        .first()
    )


def approve_partner_build(
    db: Session,
    build: PSMFPartnerBuild,
    *,
    approved_by: str,
    approval_comment: str | None = None,
    user_id: str | None = None,
) -> PSMFPartnerBuild:
    if build.build_type != "FINAL":
        raise ValueError("Утверждать можно только финальную сборку.")
    build.build_status = "approved"
    build.approved_by_text = approved_by
    build.approved_at = utcnow()
    build.approval_comment = approval_comment
    build.updated_at = utcnow()
    log_psmf_event(
        db,
        entity_type="PSMF_PARTNER_BUILD",
        entity_id=build.id,
        action="final_build_approved",
        title=f"Финальная сборка МФСФ {build.version}",
        details=f"Утвердил: {approved_by}.",
        field_name="build_status",
        old_value="final_snapshot",
        new_value="approved",
        user_id=user_id,
    )
    db.commit()
    db.refresh(build)
    return build


def inspection_package(db: Session, partner_id: str | None = None) -> dict[str, Any]:
    builds = list_partner_builds(db, partner_id=partner_id)
    final_build = next((build for build in builds if build.build_type == "FINAL"), None)
    warnings = collect_psmf_warnings(db, partner_id=partner_id)
    audit_entries = list_psmf_audit_entries(db)[:30]
    return {
        "final_build": final_build,
        "builds": builds[:10],
        "warnings": warnings,
        "audit_entries": audit_entries,
    }


