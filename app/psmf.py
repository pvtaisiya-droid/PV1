def ensure_seed_component(
    db: Session,
    *,
    code: str,
    title: str,
    component_type: str,
    parent: PSMFComponent | None,
    component_order: int,
    is_required: bool,
    is_optional: bool,
    include_if_has_content: bool,
    user_id: str | None,
    initial_version: str = "0.1",
    initial_content: str = DEFAULT_COMPONENT_TEXT,
    initial_status: str = "draft",
) -> PSMFComponent:
    component = (
        db.query(PSMFComponent)
        .filter(PSMFComponent.code == code, PSMFComponent.is_deleted.is_(False))
        .first()
    )
    created = False
    if not component:
        component = PSMFComponent(
            code=code,
            title=title,
            title_ru=title,
            original_code=code,
            original_title=title,
            component_type=component_type,
            parent_component_id=parent.id if parent else None,
            component_order=component_order,
            scope="GLOBAL",
            description=seed_description(component_type, is_required, is_optional),
            is_required=is_required,
            is_optional=is_optional,
            include_if_has_content=include_if_has_content,
            status=initial_status,
            current_version=initial_version,
        )
        db.add(component)
        db.flush()
        created = True
    else:
        fill_missing(component, "title_ru", title)
        fill_missing(component, "original_code", code)
        fill_missing(component, "original_title", title)
        fill_missing(component, "description", seed_description(component_type, is_required, is_optional))
        if not component.parent_component_id and parent:
            component.parent_component_id = parent.id
        if not component.component_order:
            component.component_order = component_order
        component.component_type = component.component_type or component_type
        component.is_required = component.is_required if component.is_required is not None else is_required
        component.is_optional = component.is_optional if component.is_optional is not None else is_optional
        component.include_if_has_content = (
            component.include_if_has_content
            if component.include_if_has_content is not None
            else include_if_has_content
        )

    active_versions = [version for version in component.versions if not version.is_deleted]
    if not active_versions:
        version = PSMFComponentVersion(
            component_id=component.id,
            version=initial_version,
            content=initial_content,
            status=initial_status,
            change_summary="Первичная версия.",
            created_by=system_actor_name(),
            created_by_text=system_actor_name(),
            approved_by_text=system_actor_name() if initial_status == "approved" else None,
            approved_at=utcnow() if initial_status == "approved" else None,
            is_locked=initial_status == "approved",
        )
        db.add(version)
        db.flush()
        component.current_version = version.version
        component.current_version_id = version.id
    elif not component.current_version_id:
        version = current_version(component) or max(active_versions, key=lambda row: version_sort_key(row.version))
        component.current_version = version.version
        component.current_version_id = version.id

    if created:
        log_psmf_event(
            db,
            entity_type="PSMF_COMPONENT",
            entity_id=component.id,
            action="created",
            title=display_title(component),
            details="Создан seed-компонент структуры МФСФ.",
            new_value=display_title(component),
            user_id=user_id,
        )
    return component


def ensure_seed_block(
    db: Session,
    *,
    component: PSMFComponent,
    code: str,
    title: str,
    block_type: str,
    block_order: int,
    source_module: str | None,
    is_required: bool,
    include_if_has_content: bool,
    user_id: str | None,
    original_code: str | None = None,
    original_title: str | None = None,
    content: str | None = None,
    partner: Partner | None = None,
    initial_version: str = "0.1",
    initial_status: str = "draft",
) -> PSMFBlock:
    block = (
        db.query(PSMFBlock)
        .filter(
            PSMFBlock.component_id == component.id,
            PSMFBlock.code == code,
            PSMFBlock.block_type == block_type,
            PSMFBlock.is_deleted.is_(False),
        )
        .first()
    )
    created = False
    if not block:
        block = PSMFBlock(
            component_id=component.id,
            original_code=original_code or code,
            original_title=original_title or title,
            code=code,
            title_ru=title,
            block_type=block_type,
            block_order=block_order,
            scope="PARTNER_SPECIFIC" if block_type == "PARTNER_BLOCK" else "GLOBAL",
            partner_id=partner.id if partner else None,
            source_module=source_module,
            is_required=is_required,
            include_if_has_content=include_if_has_content,
            status=initial_status,
        )
        db.add(block)
        db.flush()
        created = True
    else:
        fill_missing(block, "original_code", original_code or code)
        fill_missing(block, "original_title", original_title or title)
        fill_missing(block, "title_ru", title)
        if not block.block_order:
            block.block_order = block_order
        if not block.source_module and source_module:
            block.source_module = source_module
        if partner and block.block_type == "PARTNER_BLOCK":
            block.partner_id = partner.id

    active_versions = [version for version in block.versions if not version.is_deleted]
    if not active_versions:
        version = PSMFBlockVersion(
            block_id=block.id,
            version=initial_version,
            content=content if content is not None else seed_block_content(block_type),
            status=initial_status,
            change_summary="Первичная версия блока.",
            created_by_text=system_actor_name(),
            approved_by_text=system_actor_name() if initial_status == "approved" else None,
            approved_at=utcnow() if initial_status == "approved" else None,
            partner_review_status=(
                "approved"
                if block_type == "PARTNER_BLOCK" and initial_status == "approved"
                else "not_required" if block_type != "PARTNER_BLOCK" else "pending"
            ),
            partner_reviewed_by_text=(
                system_actor_name()
                if block_type == "PARTNER_BLOCK" and initial_status == "approved"
                else None
            ),
            partner_reviewed_at=(
                utcnow()
                if block_type == "PARTNER_BLOCK" and initial_status == "approved"
                else None
            ),
            is_locked=initial_status == "approved",
        )
        db.add(version)
        db.flush()
        block.current_version_id = version.id
    elif not block.current_version_id:
        block.current_version_id = max(active_versions, key=lambda row: version_sort_key(row.version)).id

    if created:
        log_psmf_event(
            db,
            entity_type="PSMF_BLOCK",
            entity_id=block.id,
            action="block_created",
            title=block.title_ru,
            details=f"Создан блок {block.block_type} внутри {component.code}.",
            new_value=block.title_ru,
            user_id=user_id,
        )
    return block


def migrate_legacy_dot_one_components(
    db: Session,
    *,
    components_by_code: dict[str, PSMFComponent],
    user_id: str | None,
) -> None:
    for old_code, old_title, parent_code, target_block_code in LEGACY_DOT_ONE_BLOCKS:
        legacy = (
            db.query(PSMFComponent)
            .options(selectinload(PSMFComponent.versions))
            .filter(PSMFComponent.code == old_code, PSMFComponent.is_deleted.is_(False))
            .first()
        )
        parent = components_by_code.get(parent_code)
        if not legacy or not parent:
            continue

        source_version = current_version(legacy)
        block = ensure_seed_block(
            db,
            component=parent,
            code=target_block_code,
            title=old_title.replace("партнера", "{{partner_name}}"),
            block_type="PARTNER_BLOCK",
            block_order=(parent.component_order or 0) + 5,
            source_module=None,
            is_required=True,
            include_if_has_content=False,
            user_id=user_id,
            original_code=old_code,
            original_title=old_title,
            content=source_version.content if source_version else seed_block_content("PARTNER_BLOCK"),
        )
        legacy.status = "replaced"
        legacy.is_active = False
        legacy.is_deleted = True
        legacy.deleted_at = utcnow()
        legacy.delete_reason = (
            "Историческое .1 приложение сохранено как данные и перенесено "
            f"в PARTNER_BLOCK {block.code} родительского приложения {parent.code}."
        )
        log_psmf_event(
            db,
            entity_type="PSMF_COMPONENT",
            entity_id=legacy.id,
            action="legacy_dot_one_converted",
            title=display_title(legacy),
            details=f"{old_code} перенесено в блок {block.code}.",
            old_value=old_code,
            new_value=block.code,
            user_id=user_id,
        )


